"""Eval driver plumbing.

The /eval SKILL is the agentic part: it runs the analyst once per gold question (fresh context,
gold blind) and captures each answer + SQL + latency. This module is the deterministic part that
does not need the model: gold loading, the grading rule, run provenance (git sha, which metrics
are currently defined), and the run record.

Two modes:

- **Local (default).** Gold lives in this repo at ``data/eval/gold.yaml`` — 10 verified cases
  against the bundled sp500 data, generated by ``data/eval/make_gold.py``. Grading is a relative
  tolerance rule and runs entirely locally; no warehouse or external repo needed.
- **External harness (optional).** Set ``AIEVALS_REPO`` to the path of an external eval-harness
  repo (exposing ``aievals.run_eval`` / ``aievals.verify_gold``) to grade against a private gold
  suite over a live warehouse. This is how the maintainers run course-grade evals; the public
  workflow does not require it.

Blind-by-construction either way: the analyst sub-agents are handed questions only
(``load_questions``). The gold answers are read ONLY at grading time, after the analyst's
answers are locked — so the runs never saw the key.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]

# Local (bundled) gold — the default.
LOCAL_GOLD_PATH = REPO_ROOT / "data" / "eval" / "gold.yaml"

# Optional external harness. Only active when the env var is explicitly set.
EVALS_REPO = Path(os.environ["AIEVALS_REPO"]) if os.environ.get("AIEVALS_REPO") else None
GOLD_PATH = (EVALS_REPO / "aievals" / "data" / "gold.yaml") if EVALS_REPO else LOCAL_GOLD_PATH
CANDIDATES_PATH = (EVALS_REPO / "aievals" / "data" / "gold_candidates.yaml") if EVALS_REPO else None


def git_sha(repo: str | Path | None = None) -> str | None:
    """Short HEAD sha of a repo, for the run record. None if not a git repo."""
    repo = Path(repo) if repo else REPO_ROOT
    try:
        return subprocess.check_output(
            ["git", "-C", str(repo), "rev-parse", "--short", "HEAD"], text=True
        ).strip()
    except Exception:
        return None


def _active_dataset(project_root: str | Path = REPO_ROOT) -> str:
    """The active dataset id, for resolving the context dir."""
    import yaml

    p = Path(project_root) / ".knowledge" / "active.yaml"
    if p.exists():
        data = yaml.safe_load(p.read_text()) or {}
        return data.get("dataset") or data.get("active") or "default"
    return "default"


def context_state(metrics_path: str | Path | None = None,
                  project_root: str | Path = REPO_ROOT) -> dict:
    """The run's context fingerprint: which metrics are DEFINED in the analyst's dictionary.

    This is what makes improvement legible — the list grows run over run as definitions are
    added, and the eval score climbs with it. Resolves the same context dir the analyst reads
    from (local under source: local, the shared cache under source: git). Best-effort: never
    crashes a run over a missing dictionary."""
    import yaml

    try:
        if metrics_path is None:
            from helpers.knowledge.context_sync import resolve_context_dir

            ctx_dir, _src = resolve_context_dir(_active_dataset(project_root), project_root)
            metrics_path = Path(ctx_dir) / "metrics" / "index.yaml"
        metrics_path = Path(metrics_path)
        if not metrics_path.exists():
            return {"defined_metrics": [], "n": 0}
        data = yaml.safe_load(metrics_path.read_text()) or {}
        names = [m.get("metric") or m.get("name")
                 for m in (data.get("metrics") or []) if isinstance(m, dict)]
        names = sorted(n for n in names if n)
        return {"defined_metrics": names, "n": len(names)}
    except Exception as e:  # pragma: no cover - defensive
        return {"defined_metrics": [], "n": 0, "error": str(e)}


# ---------------------------------------------------------------------------
# Local mode
# ---------------------------------------------------------------------------

def load_gold(gold_path: str | Path = None) -> dict:
    """Load the local gold file (cases + grading rule)."""
    import yaml

    p = Path(gold_path) if gold_path else LOCAL_GOLD_PATH
    return yaml.safe_load(p.read_text())


def load_questions(split: str | None = None, gold_path: str | Path = None) -> list[dict]:
    """Questions ONLY (id, split, question, unit) — the blind view handed to the analyst.

    The answers stay in the gold file, which is read again only by grade_local()."""
    doc = load_gold(gold_path)
    out = []
    for c in doc.get("cases", []):
        if split and c.get("split") != split:
            continue
        out.append({"id": c["id"], "split": c["split"],
                    "question": c["question"], "unit": c.get("unit")})
    return out


def grade_local(per_case_results: list[dict], split: str | None, out_dir: str | Path,
                gold_path: str | Path = None, model: str | None = None,
                extra_meta: dict | None = None) -> dict:
    """Grade locked answers against the local gold with the relative-tolerance rule and write
    a self-describing run record.

    per_case_results: [{id, answer (float), sql?, latency_s?, notes?}]. Rule: correct when
    |answer - gold| <= tolerance_pct% of |gold| (exact match when tolerance_pct is 0)."""
    doc = load_gold(gold_path)
    gold = {c["id"]: c for c in doc.get("cases", [])
            if split is None or c.get("split") == split}
    graded, n_correct = [], 0
    for r in per_case_results:
        g = gold.get(r.get("id"))
        if g is None:
            graded.append({**r, "graded": "unknown_case"})
            continue
        try:
            ans = float(r["answer"])
            tol = float(g.get("tolerance_pct", 0.0)) / 100.0
            bound = abs(g["answer"]) * tol
            ok = abs(ans - g["answer"]) <= max(bound, 1e-12 if tol == 0 else bound)
            if tol == 0:
                ok = abs(ans - g["answer"]) < 1e-9
        except (TypeError, ValueError, KeyError):
            ok = False
        n_correct += bool(ok)
        graded.append({**r, "gold": g["answer"], "tolerance_pct": g.get("tolerance_pct"),
                       "correct": bool(ok)})
    record = {
        "mode": "local",
        "split": split,
        "n_cases": len(graded),
        "n_correct": n_correct,
        "accuracy": (n_correct / len(graded)) if graded else None,
        "graded": graded,
        "meta": {"git_sha": git_sha(), "model": model, "context_state": context_state(),
                 "ts": time.strftime("%Y-%m-%dT%H:%M:%S"), **(extra_meta or {})},
    }
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"eval_run_{time.strftime('%Y%m%d_%H%M%S')}.json"
    out_path.write_text(json.dumps(record, indent=2))
    record["run_record"] = str(out_path)
    return record


# ---------------------------------------------------------------------------
# External-harness mode (optional; requires AIEVALS_REPO)
# ---------------------------------------------------------------------------

def _require_external():
    if EVALS_REPO is None:
        raise RuntimeError(
            "external eval-harness mode requires the AIEVALS_REPO environment variable to point "
            "at a harness repo. For the bundled public gold, use grade_local() instead."
        )
    if str(EVALS_REPO) not in sys.path:
        sys.path.insert(0, str(EVALS_REPO))


def get_snowflake_conn():
    """Open the analyst's Snowflake connection and return the raw DBAPI connection.

    External mode is Snowflake only, fail loud: if the manager connects to anything else
    (e.g. a local DuckDB fallback), raise instead of silently grading against the wrong engine."""
    from helpers.data.connection_manager import ConnectionManager

    cm = ConnectionManager()
    cm.connect()
    if cm.connection_type != "snowflake":
        raise RuntimeError(
            f"eval: active connection is '{cm.connection_type}', not Snowflake. External-harness "
            "mode requires Snowflake with no DuckDB fallback — connect the active dataset to "
            "Snowflake first (/setup-snowflake or /connect-data; the manifest type must be "
            "'snowflake')."
        )
    return cm._connection


def preflight(conn=None):
    """Fail-loud gate for external mode: a live Snowflake connection that answers a trivial
    probe. Raises a clear RuntimeError rather than degrading to local data."""
    conn = conn or get_snowflake_conn()
    try:
        cur = conn.cursor()
        cur.execute("select 1")
        cur.fetchone()
    except Exception as e:
        raise RuntimeError(
            f"eval preflight: Snowflake probe failed ({e}). Fix the connection; there is no "
            "local fallback in external mode."
        ) from e
    return conn


def grade(per_case_results, split, out_dir, conn, gold_path=None,
          model=None, extra_meta=None):
    """Grade the locked answers against the BLIND external gold and write the full run record.

    Imports the harness from the AIEVALS_REPO repo. The gold is read only at this point, after
    the analyst answers are fixed, so the runs stayed blind. The run record carries git_sha +
    model + context_state so it is self-describing."""
    _require_external()
    from aievals.run_eval import run_eval

    meta = {"git_sha": git_sha(), "model": model, "context_state": context_state()}
    if extra_meta:
        meta.update(extra_meta)
    return run_eval(str(gold_path or GOLD_PATH), per_case_results, conn, out_dir=str(out_dir),
                    split=split, meta=meta)


def verify_candidates(cases_path=None, split=None):
    """External mode: run every candidate gold sql against Snowflake and print which return a
    real number. Use before merging candidates into the trusted suite (gold discipline: the sql
    must run and be signed off)."""
    _require_external()
    from aievals.verify_gold import verify_cases, format_report

    conn = preflight()
    results = verify_cases(str(cases_path or CANDIDATES_PATH), conn, split=split)
    print(format_report(results))
    return results
